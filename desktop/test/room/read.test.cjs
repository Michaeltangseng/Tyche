const assert = require('node:assert/strict')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const test = require('node:test')
const { openRoomDatabase } = require('../../src/room/db.cjs')
const { createRoomRepository } = require('../../src/room/repository.cjs')
const { createTimeline } = require('../../src/room/timeline.cjs')
const { createToolDispatcher } = require('../../src/room/tools/dispatcher.cjs')
const { registerReadChatTool } = require('../../src/room/tools/read.cjs')

test('read_chat returns a page and sees messages appended after a prior call', async t => {
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'meldwork-room-v2-'))
  t.after(() => fs.rmSync(directory, { recursive: true, force: true }))
  const roomDb = openRoomDatabase({ directory })
  const repo = createRoomRepository(roomDb)
  const roomId = repo.createRoom({ name: 'R', workspace: directory })
  const chatId = repo.createChat({ roomId, title: 'C' })
  const roleId = repo.createRole({ chatId, displayName: 'A', provider: 'claude', prompt: 'p' })
  repo.addParticipant({ chatId, roleId })
  const timeline = createTimeline({ roomDb, repository: repo })
  timeline.append({ chatId, authorType: 'user', authorId: 'user', content: 'first' })
  const dispatcher = createToolDispatcher({ roomDb, repository: repo })
  registerReadChatTool({ dispatcher, timeline, repository: repo })
  dispatcher.bindRun('run1', { chatId, roleId, allowedTools: ['read_chat'] })
  const first = await dispatcher.invoke({ runId: 'run1', callId: 'read-1', name: 'read_chat', args: { limit: 10 } })
  timeline.append({ chatId, authorType: 'user', authorId: 'user', content: 'later' })
  const second = await dispatcher.invoke({ runId: 'run1', callId: 'read-2', name: 'read_chat', args: { limit: 10 } })
  assert.equal(first.hasMore, false)
  assert.equal(first.messages.length, 1)
  assert.equal(second.messages.some(message => message.content === 'later'), true)
  roomDb.close()
})

test('read_chat paginates with beforeSeq', async t => {
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'meldwork-room-v2-'))
  t.after(() => fs.rmSync(directory, { recursive: true, force: true }))
  const roomDb = openRoomDatabase({ directory })
  const repo = createRoomRepository(roomDb)
  const roomId = repo.createRoom({ name: 'R', workspace: directory })
  const chatId = repo.createChat({ roomId, title: 'C' })
  const roleId = repo.createRole({ chatId, displayName: 'A', provider: 'claude', prompt: 'p' })
  repo.addParticipant({ chatId, roleId })
  const timeline = createTimeline({ roomDb, repository: repo })
  for (const content of ['one', 'two', 'three']) timeline.append({ chatId, authorType: 'user', authorId: 'user', content })
  const dispatcher = createToolDispatcher({ roomDb, repository: repo })
  registerReadChatTool({ dispatcher, timeline, repository: repo })
  dispatcher.bindRun('run1', { chatId, roleId, allowedTools: ['read_chat'] })
  const page = await dispatcher.invoke({ runId: 'run1', callId: 'read-1', name: 'read_chat', args: { beforeSeq: 3, limit: 2 } })
  assert.deepEqual(page.messages.map(message => message.content), ['one', 'two'])
  assert.equal(page.hasMore, false)
  roomDb.close()
})

test('read_chat hides captain-only rows from non-captains', async t => {
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'meldwork-room-v2-'))
  t.after(() => fs.rmSync(directory, { recursive: true, force: true }))
  const roomDb = openRoomDatabase({ directory })
  const repo = createRoomRepository(roomDb)
  const roomId = repo.createRoom({ name: 'R', workspace: directory })
  const chatId = repo.createChat({ roomId, title: 'C' })
  const a = repo.createRole({ chatId, displayName: 'A', provider: 'claude', prompt: 'p' })
  const captain = repo.createRole({ chatId, displayName: 'Captain', provider: 'claude', prompt: 'p', isCaptain: true })
  repo.addParticipant({ chatId, roleId: a })
  repo.addParticipant({ chatId, roleId: captain })
  const timeline = createTimeline({ roomDb, repository: repo })
  timeline.append({ chatId, authorType: 'user', authorId: 'user', content: 'public' })
  timeline.append({ chatId, authorType: 'system', authorId: 'system', kind: 'captain_review',
    content: 'secret', audience: 'captain', status: 'done' })
  const dispatcher = createToolDispatcher({ roomDb, repository: repo })
  registerReadChatTool({ dispatcher, timeline, repository: repo })
  dispatcher.bindRun('worker', { chatId, roleId: a, allowedTools: ['read_chat'] })
  dispatcher.bindRun('captain', { chatId, roleId: captain, allowedTools: ['read_chat'] })
  const workerPage = await dispatcher.invoke({ runId: 'worker', callId: 'w1', name: 'read_chat', args: { limit: 10 } })
  const captainPage = await dispatcher.invoke({ runId: 'captain', callId: 'c1', name: 'read_chat', args: { limit: 10 } })
  assert.equal(workerPage.messages.some(message => message.content === 'secret'), false)
  assert.equal(captainPage.messages.some(message => message.content === 'secret'), true)
  roomDb.close()
})
